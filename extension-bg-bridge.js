'use strict';

/**
 * Chrome APIs for an extension's background service worker.
 *
 * A worker gets no preload, so there is no ipcRenderer to use. It does have
 * fetch, so this shim is written into the extension and talks to the main
 * process over a loopback endpoint. A per-session token, baked into this file
 * at patch time, gates every request.
 *
 * chrome.webRequest is not here. Blocking needs a synchronous answer before a
 * request goes out and this transport is async, so a stub would let a content
 * blocker start up and then block nothing.
 */

/** Build the shim source, with the session's API token baked in. */
function buildBackgroundShim(token, port) {
  const TOKEN = JSON.stringify(String(token || ''));
  const BASE = JSON.stringify('http://127.0.0.1:' + (Number(port) || 0) + '/');

  return `/* Generated by Privoo. Adds Chrome extension APIs Electron omits. */
(function () {
  'use strict';
  var g = (typeof globalThis !== 'undefined') ? globalThis : self;
  var chrome = g.chrome || (g.chrome = {});
  if (chrome.__privooBgShim) { return; }

  var TOKEN = ${TOKEN};
  var BASE = ${BASE};

  function post(method, args) {
    return fetch(BASE + 'call', {
      method: 'POST',
      // text/plain is CORS-safelisted, so this needs no preflight. The body is
      // still JSON; only the header is chosen to keep the request simple.
      headers: { 'content-type': 'text/plain' },
      body: JSON.stringify({ token: TOKEN, method: method, args: args || [] })
    }).then(function (r) { return r.json(); }).then(function (res) {
      if (res && res.error) { throw new Error(res.error); }
      return res ? res.value : undefined;
    });
  }

  // Chrome's APIs take a callback or return a promise; support both.
  function settle(p, cb) {
    if (typeof cb === 'function') {
      p.then(
        function (v) { try { cb(v); } catch (e) {} },
        function () { try { cb(undefined); } catch (e) {} }
      );
      return undefined;
    }
    return p;
  }

  // ── Events ──────────────────────────────────────────────────────────────
  // One long-poll for the whole worker: it hangs until the main process has
  // something, then immediately re-opens. No timers, no busy waiting.
  var listeners = {};
  var polling = false;
  var cursor = 0;

  function poll() {
    if (polling) { return; }
    polling = true;
    fetch(BASE + 'events?token=' + encodeURIComponent(TOKEN) + '&since=' + cursor)
      .then(function (r) { return r.json(); })
      .then(function (batch) {
        polling = false;
        if (batch && typeof batch.cursor === 'number') { cursor = batch.cursor; }
        var evs = (batch && batch.events) || [];
        for (var i = 0; i < evs.length; i++) {
          var set = listeners[evs[i].name];
          if (!set) { continue; }
          for (var j = 0; j < set.length; j++) {
            try { set[j](evs[i].payload); } catch (e) {}
          }
        }
        if (Object.keys(listeners).length) { poll(); }
      })
      .catch(function () {
        polling = false;
        // Back off a little so a persistent failure cannot spin.
        if (Object.keys(listeners).length) { setTimeout(poll, 2000); }
      });
  }

  function makeEvent(name) {
    return {
      addListener: function (fn) {
        if (typeof fn !== 'function') { return; }
        if (!listeners[name]) {
          listeners[name] = [];
          post('events.subscribe', [name]).catch(function () {});
        }
        listeners[name].push(fn);
        poll();
      },
      removeListener: function (fn) {
        var set = listeners[name];
        if (!set) { return; }
        var i = set.indexOf(fn);
        if (i >= 0) { set.splice(i, 1); }
      },
      hasListener: function (fn) {
        return !!listeners[name] && listeners[name].indexOf(fn) >= 0;
      },
      hasListeners: function () {
        return !!listeners[name] && listeners[name].length > 0;
      }
    };
  }

  function args2(a, b) { return (typeof a === 'function') ? a : b; }

  // ── The namespaces ──────────────────────────────────────────────────────
  if (!chrome.cookies) {
    chrome.cookies = {
      get: function (d, cb) { return settle(post('cookies.get', [d]), cb); },
      getAll: function (d, cb) { return settle(post('cookies.getAll', [d]), cb); },
      set: function (d, cb) { return settle(post('cookies.set', [d]), cb); },
      remove: function (d, cb) { return settle(post('cookies.remove', [d]), cb); },
      getAllCookieStores: function (cb) { return settle(post('cookies.getAllCookieStores', []), cb); },
      onChanged: makeEvent('cookies.onChanged')
    };
  }

  if (!chrome.webNavigation) {
    chrome.webNavigation = {
      getFrame: function (d, cb) { return settle(post('webNavigation.getFrame', [d]), cb); },
      getAllFrames: function (d, cb) { return settle(post('webNavigation.getAllFrames', [d]), cb); },
      onBeforeNavigate: makeEvent('webNavigation.onBeforeNavigate'),
      onCommitted: makeEvent('webNavigation.onCommitted'),
      onDOMContentLoaded: makeEvent('webNavigation.onDOMContentLoaded'),
      onCompleted: makeEvent('webNavigation.onCompleted'),
      onErrorOccurred: makeEvent('webNavigation.onErrorOccurred'),
      onCreatedNavigationTarget: makeEvent('webNavigation.onCreatedNavigationTarget'),
      onReferenceFragmentUpdated: makeEvent('webNavigation.onReferenceFragmentUpdated'),
      onHistoryStateUpdated: makeEvent('webNavigation.onHistoryStateUpdated')
    };
  }

  if (!chrome.permissions) {
    chrome.permissions = {
      getAll: function (cb) { return settle(Promise.resolve({ permissions: [], origins: [] }), cb); },
      contains: function (p, cb) { return settle(Promise.resolve(true), cb); },
      request: function (p, cb) { return settle(Promise.resolve(true), cb); },
      remove: function (p, cb) { return settle(Promise.resolve(false), cb); },
      onAdded: makeEvent('permissions.onAdded'),
      onRemoved: makeEvent('permissions.onRemoved')
    };
  }

  if (!chrome.windows) {
    chrome.windows = {
      WINDOW_ID_CURRENT: -2,
      WINDOW_ID_NONE: -1,
      get: function (id, a, b) { return settle(post('windows.get', []), args2(a, b)); },
      getCurrent: function (a, b) { return settle(post('windows.get', []), args2(a, b)); },
      getLastFocused: function (a, b) { return settle(post('windows.get', []), args2(a, b)); },
      getAll: function (a, b) { return settle(post('windows.getAll', []), args2(a, b)); },
      create: function (a, b) { return settle(post('windows.get', []), args2(a, b)); },
      update: function (id, a, b) { return settle(post('windows.get', []), args2(a, b)); },
      remove: function (id, cb) { return settle(Promise.resolve(undefined), cb); },
      onCreated: makeEvent('windows.onCreated'),
      onRemoved: makeEvent('windows.onRemoved'),
      onFocusChanged: makeEvent('windows.onFocusChanged'),
      onBoundsChanged: makeEvent('windows.onBoundsChanged')
    };
  }

  if (!chrome.contextMenus) {
    chrome.contextMenus = {
      create: function (props, cb) {
        var id = (props && props.id) || ('privoo_' + Math.random().toString(36).slice(2, 9));
        post('contextMenus.create', [Object.assign({}, props, { id: id })]).catch(function () {});
        if (typeof cb === 'function') { try { cb(); } catch (e) {} }
        return id;
      },
      update: function (id, props, cb) { return settle(post('contextMenus.update', [id, props]), cb); },
      remove: function (id, cb) { return settle(post('contextMenus.remove', [id]), cb); },
      removeAll: function (cb) { return settle(post('contextMenus.removeAll', []), cb); },
      onClicked: makeEvent('contextMenus.onClicked')
    };
  }

  if (!chrome.notifications) {
    chrome.notifications = {
      create: function (a, b, c) {
        var id = (typeof a === 'string') ? a : ('privoo_' + Math.random().toString(36).slice(2, 9));
        var opts = (typeof a === 'string') ? b : a;
        var cb = (typeof a === 'string') ? c : b;
        return settle(post('notifications.create', [id, opts]).then(function () { return id; }), cb);
      },
      clear: function (id, cb) { return settle(post('notifications.clear', [id]), cb); },
      getAll: function (cb) { return settle(post('notifications.getAll', []), cb); },
      update: function (id, opts, cb) { return settle(Promise.resolve(false), cb); },
      onClicked: makeEvent('notifications.onClicked'),
      onClosed: makeEvent('notifications.onClosed'),
      onButtonClicked: makeEvent('notifications.onButtonClicked')
    };
  }

  if (!chrome.commands) {
    chrome.commands = {
      getAll: function (cb) { return settle(post('commands.getAll', [String((g.location && g.location.href) || '')]), cb); },
      reset: function (name, cb) { return settle(Promise.resolve(undefined), cb); },
      update: function (d, cb) { return settle(Promise.resolve(undefined), cb); },
      onCommand: makeEvent('commands.onCommand')
    };
  }

  if (!chrome.idle) {
    chrome.idle = {
      queryState: function (secs, cb) { return settle(post('idle.queryState', [secs]), cb); },
      getAutoLockDelay: function (cb) { return settle(Promise.resolve(0), cb); },
      setDetectionInterval: function () {},
      onStateChanged: makeEvent('idle.onStateChanged')
    };
  }

  // Extensions written against the WebExtension spec read \`browser\`, and many
  // do \`self.browser || self.chrome\`. If the runtime already provides its own
  // \`browser\` object, adding namespaces only to \`chrome\` would leave the one
  // the extension actually reads untouched.
  if (typeof g.browser === 'undefined') {
    g.browser = chrome;
  } else if (g.browser !== chrome) {
    var names = ['cookies', 'webNavigation', 'permissions', 'windows',
                 'contextMenus', 'notifications', 'idle', 'commands'];
    for (var n = 0; n < names.length; n++) {
      if (!g.browser[names[n]] && chrome[names[n]]) {
        try { g.browser[names[n]] = chrome[names[n]]; } catch (e) {}
      }
    }
  }

  chrome.__privooBgShim = true;
  g.__privooBgShimApplied = true;

  // Tells the main process the bridge is live in this worker. Also the only
  // way to confirm it ran when the worker fails to register and cannot be
  // inspected.
  try { post('bridge.hello', [String((g.location && g.location.href) || '')]).catch(function () {}); } catch (e) {}
})();
`;
}

module.exports = { buildBackgroundShim };
